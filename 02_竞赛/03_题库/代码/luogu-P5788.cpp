// 题号：luogu-P5788
// 题名：【模板】单调栈
// 链接：https://www.luogu.com.cn/problem/P5788
// 难度：入门
// 主知识点：3-5 单调栈的定义与维护
// 副知识点：3-6 四类边界问题与取答案时机
// 状态：已通过
//
// 题意：给定长度 n 的序列 a，对每个 i 输出 a[i] 右边第一个大于 a[i] 的元素的下标，
//       不存在则输出 0。
//
// 数据范围：n ≤ 3×10^6
//
// 复杂度：时间 O(n)　空间 O(n)
// 编译：g++ -std=c++17 -O2
//
// 易错点：
//   1. 弹出条件必须写 <=，写 < 会让相等元素互相挡住，得到错误答案
//   2. n 达 3×10^6，必须关闭流同步，否则读入可能超时
//   3. 数组要按上界开，并留少量冗余
// ============================================================================

#include <cstdio>
#include <stack>
#include <iostream>
using namespace std;

const int MAXN = 3000000 + 5;   // 边界：按题面上界 n ≤ 3×10^6 加 5 冗余

int n;
int a[MAXN];
int ans[MAXN];
stack<int> s;                   // 栈内存的是下标，不是值

int main() {
    // 关闭流同步并解绑，使 cin 的读入速度超过 scanf（n 达 3×10^6，这一步是必需的）
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    cin >> n;
    for (int i = 1; i <= n; ++i) {
        cin >> a[i];
    }

    // 从右往左扫，维护一个从栈底到栈顶单调递减的栈
    // 这样栈里保存的都是「可能成为某个左侧元素答案」的候选下标
    for (int i = n; i >= 1; --i) {
        // 边界：必须写 <= 而不是 <
        // 若写 <，相等的元素会互相挡住，导致答案错误
        while (!s.empty() && a[s.top()] <= a[i]) {
            s.pop();            // 栈顶不比我大，挡不住我，弹走
        }
        // 边界：取栈顶前必须判空，栈空说明右边没有更大的元素
        ans[i] = s.empty() ? 0 : s.top();
        s.push(i);              // 自己入栈，去挡住后面更小的元素
    }

    // 输出：空格分隔，最后一个元素后换行
    for (int i = 1; i <= n; ++i) {
        cout << ans[i] << " \n"[i == n];
    }

    return 0;
}
